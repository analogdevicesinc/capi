#!/usr/bin/env python3
"""Resolve a Kconfig tree into CMake CONFIG_* variables.

Loads the unified Kconfig tree written by sdk/cmake/kconfig.cmake, merges
each --fragment on top of it in the order given (a board's defconfig
first, then the application's project.conf), and writes a CMake script
holding one set(CONFIG_<SYMBOL> <value>) per resolved symbol.
"""

import argparse
import sys
from pathlib import Path

import kconfiglib


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kconfig", required=True, type=Path,
                        help="the unified Kconfig tree to resolve")
    parser.add_argument("--out", required=True, type=Path,
                        help="CMake script to write")
    parser.add_argument("--fragment", nargs="*", default=[], type=Path,
                        help="config fragments, merged in the order given")
    args = parser.parse_args()

    kconf = kconfiglib.Kconfig(str(args.kconfig))

    # Fragments merge rather than replace, so a board defconfig may enable
    # CONFIG_UART_MAXIM before project.conf turns on the CONFIG_UART it
    # needs. Re-assigning a symbol its current value is normal here, so
    # only that kconfiglib warning is silenced.
    kconf.warn_assign_redun = False
    for fragment in args.fragment:
        kconf.load_config(str(fragment), replace=False)

    lines = [f"# Generated by {Path(__file__).name} -- do not edit.\n"]
    for sym in kconf.unique_defined_syms:
        # Empty means kconfiglib would not write the symbol out: its
        # dependencies are unmet, so emitting it would leak an inactive
        # symbol and its default into the CMake config.
        if not sym.config_string:
            continue
        if sym.orig_type in (kconfiglib.BOOL, kconfiglib.TRISTATE):
            value = "ON" if sym.tri_value != 0 else "OFF"
        else:
            value = sym.str_value
        # Escaped, or a value with a quote breaks out of the set().
        escaped_value = value.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'set(CONFIG_{sym.name} "{escaped_value}")\n')
    content = "".join(lines)

    # Only rewrite on a real change: the output is include()d, so touching
    # it every configure would loop.
    if not args.out.exists() or args.out.read_text() != content:
        args.out.write_text(content)


if __name__ == "__main__":
    sys.exit(main())
